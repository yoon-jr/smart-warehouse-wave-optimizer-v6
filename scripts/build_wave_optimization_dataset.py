from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import pandas as pd

from smart_warehouse.wave_optimization import (
    MODEL_FEATURE_COLUMNS,
    RouteOptimizationConfig,
    build_wave_optimization_dataset,
)
from smart_warehouse.warehouse import WarehouseMap


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build one leakage-safe ML row per Footwear WMS wave and create "
            "route-optimization benefit labels using NN + bounded 2-opt."
        )
    )
    parser.add_argument(
        "--tasks",
        type=Path,
        default=Path("data/footwear_replay_tasks.csv"),
        help="Prepared task CSV generated by scripts.prepare_footwear_data.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/wave_optimization_dataset.csv"),
    )
    parser.add_argument("--max-waves", type=int, default=None)
    parser.add_argument("--depot-x", type=int, default=1)
    parser.add_argument("--depot-y", type=int, default=1)
    parser.add_argument("--two-opt-passes", type=int, default=8)
    parser.add_argument("--two-opt-span", type=int, default=60)
    parser.add_argument("--seconds-per-grid-step", type=float, default=2.0)
    parser.add_argument("--seconds-per-pick-line", type=float, default=6.0)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not args.tasks.exists():
        raise FileNotFoundError(
            f"Prepared task file not found: {args.tasks}. "
            "Run `python -m scripts.prepare_footwear_data --dataset-dir <folder> --minutes-per-wave 60` first."
        )

    started = time.perf_counter()
    tasks = pd.read_csv(args.tasks, low_memory=False)
    warehouse = WarehouseMap.create_default()
    config = RouteOptimizationConfig(
        depot=(args.depot_x, args.depot_y),
        two_opt_max_passes=args.two_opt_passes,
        two_opt_candidate_span=args.two_opt_span,
        seconds_per_grid_step=args.seconds_per_grid_step,
        seconds_per_pick_line=args.seconds_per_pick_line,
    )
    dataset = build_wave_optimization_dataset(
        tasks,
        warehouse=warehouse,
        config=config,
        max_waves=args.max_waves,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    dataset.to_csv(args.output, index=False)

    elapsed = time.perf_counter() - started
    summary = {
        "input_tasks": int(len(tasks)),
        "waves": int(len(dataset)),
        "output": str(args.output),
        "runtime_seconds": round(elapsed, 3),
        "mean_original_distance": round(float(dataset["original_route_distance"].mean()), 3),
        "mean_optimized_distance": round(float(dataset["optimized_route_distance"].mean()), 3),
        "mean_saving_pct": round(float(dataset["saving_pct"].mean()), 3),
        "median_saving_pct": round(float(dataset["saving_pct"].median()), 3),
        "improved_wave_pct": round(float((dataset["distance_saved"] > 0).mean() * 100), 3),
        "model_feature_count": len(MODEL_FEATURE_COLUMNS),
        "distance_definition": "shortest-path grid steps on the simulator warehouse, depot-to-stops-to-depot",
        "fairness_rule": "original and optimized routes use the same unique physical stop set",
    }
    summary_path = args.output.with_suffix(".summary.json")
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print("\nTop 10 waves by actual route saving")
    print(
        dataset.nlargest(10, "saving_pct")[
            [
                "wave_id",
                "task_count",
                "unique_grid_stop_count",
                "original_route_distance",
                "optimized_route_distance",
                "saving_pct",
            ]
        ].to_string(index=False)
    )


if __name__ == "__main__":
    main()
